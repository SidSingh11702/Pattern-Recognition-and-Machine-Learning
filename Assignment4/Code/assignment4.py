"""**Principal Component Analysis (PCA)**"""

# Mean estimation
def Mu(X):
  return np.sum(X,axis=0)/len(X)

# Covariance matrix estimation 
def Sigma(X,mu):
  N = len(X) 
  d = len(mu)
  X = np.reshape(X,(N,d,1))
  mu = np.reshape(mu,(d,1))
  sum = np.zeros((d,d))
  for n in range(N):
    sum += (X[n]-mu)@((X[n]-mu).T)
  return sum/(N-1)

def PCA(X1,K,X2):
  mu = Mu(X1)
  sigma = Sigma(X1,mu)
  eig_vals,eig_vecs = np.linalg.eig(sigma)
  seq = np.argsort(np.absolute(eig_vals))[::-1]
  eig_vecs = eig_vecs.T
  eig_vecs = eig_vecs[seq]
  return ((np.absolute(eig_vecs)[:K])@(X1.T)).T,((np.absolute(eig_vecs)[:K])@(X2.T)).T

"""**Linear Discriminant Analysis (LDA)**"""

# Calculation of within-class scatter matrix
def SW(X,mu):
  d = len(X[0][0])
  res = np.zeros((d,d))
  for clas in range(len(X)):
    for data in X[clas]:
      res += (np.array(data)-mu[clas])@((np.array(data)-mu[clas]).T)
  return res

# Calculation of between-class scatter matrix
def SB(X,mu,mu_overall):
  d = len(mu[0])
  res = np.zeros((d,d))
  for clas in range(len(mu)):
    res += len(X[clas])*(mu[clas]-mu_overall)@((mu[clas]-mu_overall).T)
  return res

def LDA(X1,X1_classwise,K,X2):
  mu = []
  mu_overall = Mu(X1)
  for clas in X1_classwise:
    mu.append(Mu(clas))
  sw = SW(X1_classwise,np.array(mu))
  # To make the matrix non-singular
  for i in range(len(sw)):
    sw[i,i] += 1e-9
  sb = SB(X1_classwise,np.array(mu),mu_overall)
  eig_vals,eig_vecs = np.linalg.eig(np.linalg.inv(sw)@sb)
  seq = np.argsort(np.absolute(eig_vals))[::-1]
  eig_vecs = eig_vecs.T
  eig_vecs = eig_vecs[seq]
  return ((np.absolute(eig_vecs)[:K])@(X1.T)).T,((np.absolute(eig_vecs)[:K])@(X2.T)).T

"""**K Nearest Neighbour (KNN) model**"""

def comp(x):
  return x[0]

# K Nearest Neighbours
def KNN(X,K,Train_data):
  distances = []
  for clas in range(len(Train_data)):
    for example in Train_data[clas]:
      distances.append([np.linalg.norm(np.array(X)-np.array(example)),clas])
  distances.sort(key=comp)
  ans = -1
  cnts = np.zeros(len(Train_data))
  for clas in range(len(Train_data)):
    cnt = 0
    for i in range(K):
      if distances[i][1] == clas:
        cnt+=1
    if cnt > ans:
      ans = clas
    elif cnt == ans:
      if random.randint(0,1) == 1:
        ans = clas
    cnts[clas] = cnt
  return cnts,ans

