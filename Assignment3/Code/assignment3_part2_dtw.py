def conf_matrix(tc,pc):
  n = len(np.unique(tc))
  Con_Matrix1 = np.zeros((n,n))
  for i in range(len(tc)):
    Con_Matrix1[int(tc[i])-1][int(pc[i])-1]+=1
  
  c = []
  r = []
  s=0
  for i in range(len(Con_Matrix1)):
    c.append(Con_Matrix1[i][i]/np.sum(Con_Matrix1[i])*100)
    r.append(Con_Matrix1[i][i]/np.sum(Con_Matrix1.T[i])*100)
    s+=Con_Matrix1[i][i]

  r.append(s/np.sum(Con_Matrix1)*100)
    
  Con_Matrix1 = np.c_[Con_Matrix1,c]
  Con_Matrix1 = np.vstack((Con_Matrix1,r))

  classes = []
  for i in range(n):
    classes.append("class "+str(i+1))
  font = {'family': 'serif',
          'color':  'red',
          'weight': 'bold',
          'size': 16,
          }
  ax = sns.heatmap(Con_Matrix1, annot=True, fmt="g")
  ax.xaxis.set_ticklabels(classes)
  plt.title('Confusion Matrix',fontdict = font)
  ax.set_xlabel('Predicted',fontdict = font)
  ax.set_ylabel('True',fontdict = font)
  ax.yaxis.set_ticklabels(classes)
  plt.show()

