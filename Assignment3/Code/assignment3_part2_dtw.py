def min_of_three(x,y,z):
  if x < y:
    if x < z:
      return x
    else:
      return z
  else:
    if y < z:
      return y
    else:
      return z

# Computes the DTW distance between X and Y
def DTW(X,Y):
  if len(X)<len(Y):
    return DTW(Y,X)
  M = len(X)
  N = len(Y)
  dtw = np.full((M+1,N+1),np.inf)
  dtw[0,0] = 0
  for i in range(1,M+1):    
    for j in range(1,N+1):  
      # print("sd")
      dtw[i,j] = min_of_three(dtw[i-1,j],dtw[i,j-1],dtw[i-1,j-1])+np.linalg.norm(X[i-1]-Y[j-1])
      # print("ed")
  return dtw[M,N]

